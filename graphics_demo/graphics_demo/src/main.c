// menu opening function. Top and Bottom button pressed at same time opens the menu.
int menuOpen(int Open)
{
	// Bit 8 == Bottom button / Bit 11 == Top button
	if (!(GPIOB->IDR & (1 << 8)) && !(GPIOB->IDR & (1 << 11)))
	{
		int selected = 0; // 0 = resume , 1 = reset
		delay(10000);
		printTextX2("Menu", 10, 20, RGBToWord(0xff, 0xff, 0), 0);
		printTextX2("Resume", 10, 40, RGBToWord(0xff, 0xff, 0), 0);
		printTextX2("Reset", 10, 60, RGBToWord(0xff, 0xff, 0), 0);

		while (1)
		{
			if (selected == 0)
			{
				// resume button button becomes red
				printTextX2("Resume", 10, 40, RGBToWord(255, 9, 0), 0);
				printTextX2("Reset", 10, 60, RGBToWord(0xff, 0xff, 0), 0);
			}
			else
			{
				// reset button becomes red
				printTextX2("Resume", 10, 40, RGBToWord(255, 255, 0), 0);
				printTextX2("Reset", 10, 60, RGBToWord(255, 9, 0), 0);
			}
			if (!(GPIOB->IDR = GPIOB->IDR && (1 << 8)))
			{
				// moving the button down one
				selected = (selected + 1) % 2;
				// releasing the button
				while (GPIOB->IDR != (1 << 8))
				{
				}
			}
			if (!(GPIOB->IDR = GPIOB->IDR && (1 << 11)))
			{
				// moving the button up one
				selected = (selected + 1) % 2;
				// releasing the button
				while (GPIOB->IDR != (1 << 11))
				{
				}
			}
			return 0;
		}
	}
}
void loop()
{
	fillRectangle(0, 7, 128, 170, 0);
	static uint32_t lastSecond = 0;
	static uint32_t gameTime = 0;

	if (milliseconds - lastSecond >= 1000)
	{
		lastSecond = milliseconds;
		gameTime++;
	}

	char buffer[20];
	sprintf(buffer, "Time: %lu s", gameTime);

	printText(buffer, 0, 0, 0xFFFF, 0x0000);
}

// menu closing function. Top & bottom button pressed at the same time if menu is already open closes it
int menuClosed(int Closed)
{
	if ((GPIOB->IDR = GPIOB->IDR |= (1 << 8) == 0) && (GPIOB->IDR = GPIOB->IDR |= (1 << 11) == 0))
	{
		return 0;
	}
	else
	{
		return 1;
	}
}

void initSysTick(void)
{
	SysTick->LOAD = 48000;
	SysTick->CTRL = 7;
	SysTick->VAL = 10;
	__asm(" cpsie i "); // enable interrupts
}
void SysTick_Handler(void)
{
	milliseconds++;
}
void initClock(void)
{
	// This is potentially a dangerous function as it could
	// result in a system with an invalid clock signal - result: a stuck system
	// Set the PLL up
	// First ensure PLL is disabled
	RCC->CR &= ~(1u << 24);
	while ((RCC->CR & (1 << 25)))
		; // wait for PLL ready to be cleared

	// Warning here: if system clock is greater than 24MHz then wait-state(s) need to be
	// inserted into Flash memory interface

	FLASH->ACR |= (1 << 0);
	FLASH->ACR &= ~((1u << 2) | (1u << 1));
	// Turn on FLASH prefetch buffer
	FLASH->ACR |= (1 << 4);
	// set PLL multiplier to 12 (yielding 48MHz)
	RCC->CFGR &= ~((1u << 21) | (1u << 20) | (1u << 19) | (1u << 18));
	RCC->CFGR |= ((1 << 21) | (1 << 19));

	// Need to limit ADC clock to below 14MHz so will change ADC prescaler to 4
	RCC->CFGR |= (1 << 14);

	// and turn the PLL back on again
	RCC->CR |= (1 << 24);
	// set PLL as system clock source
	RCC->CFGR |= (1 << 1);
}
void delay(volatile uint32_t dly)
{
	uint32_t end_time = dly + milliseconds;
	while (milliseconds != end_time)
		__asm(" wfi "); // sleep
}

void enablePullUp(GPIO_TypeDef *Port, uint32_t BitNumber)
{
	Port->PUPDR = Port->PUPDR & ~(3u << BitNumber * 2); // clear pull-up resistor bits
	Port->PUPDR = Port->PUPDR | (1u << BitNumber * 2);	// set pull-up bit
}
void pinMode(GPIO_TypeDef *Port, uint32_t BitNumber, uint32_t Mode)
{
	/*
	 */
	uint32_t mode_value = Port->MODER;
	Mode = Mode << (2 * BitNumber);
	mode_value = mode_value & ~(3u << (BitNumber * 2));
	mode_value = mode_value | Mode;
	Port->MODER = mode_value;
}
int isInside(uint16_t x1, uint16_t y1, uint16_t w, uint16_t h, uint16_t px, uint16_t py)
{
	// checks to see if point px,py is within the rectange defined by x,y,w,h
	uint16_t x2, y2;
	x2 = x1 + w;
	y2 = y1 + h;
	int rvalue = 0;
	if ((px >= x1) && (px <= x2))
	{
		// ok, x constraint met
		if ((py >= y1) && (py <= y2))
			rvalue = 1;
	}
	return rvalue;
}

void setupIO()
{
	RCC->AHBENR |= (1 << 18) + (1 << 17); // enable Ports A and B
	display_begin();
	pinMode(GPIOB, 4, 0);
	pinMode(GPIOB, 5, 0);
	pinMode(GPIOA, 8, 0);
	pinMode(GPIOA, 11, 0);
	enablePullUp(GPIOB, 4);
	enablePullUp(GPIOB, 5);
	enablePullUp(GPIOA, 11);
	enablePullUp(GPIOA, 8);
}
